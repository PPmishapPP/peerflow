package ru.peerflow.realtime;

/**
 * Что произошло — вид события в потоке {@code /api/events}
 * ({@code BR-DISC-1}, {@code BR-VOTE-4}, {@code BR-LIFE-7}).
 *
 * <p>Набор намеренно короткий: поток обслуживает «горячие» поверхности —
 * живую ленту обсуждения, счётчики голосов и новые отчёты. Всё остальное
 * клиент получает обычным запросом, когда открывает экран; превращать поток в
 * шину для всего приложения в MVP незачем.
 *
 * <p>Имя каждого события — часть контракта с клиентом: по нему Android решает,
 * что перезапросить. Поэтому строки фиксированы, а не собираются из имени
 * enum на ходу.
 */
public enum EventType {

    /** Новое сообщение или ответ в обсуждении задачи ({@code BR-DISC-1}). */
    MESSAGE_POSTED,

    /** Изменились счётчики голосов задачи ({@code BR-VOTE-4}). */
    VOTE_CHANGED,

    /** Лидер опубликовал отчёт ({@code BR-LIFE-7}). */
    REPORT_POSTED,

    /** Сообщество закрыло задачу ({@code BR-LIFE-9}). */
    TASK_CLOSED
}
