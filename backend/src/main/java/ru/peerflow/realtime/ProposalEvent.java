package ru.peerflow.realtime;

import java.util.UUID;

/**
 * Событие задачи для потока {@code /api/events} ({@code BR-DISC-1},
 * {@code BR-VOTE-4}, {@code BR-LIFE-7}).
 *
 * <p>Событие — уведомление, а не данные: в нём только «что случилось» и «по
 * какой задаче». Так клиент не зависит от формата ответов и не показывает
 * устаревшие подробности — он перезапрашивает экран и получает согласованное
 * состояние, посчитанное сервером.
 *
 * <p>Задача обязательна: события адресованы людям конкретного сообщества, и
 * подписка фильтруется по задачам этого сообщества
 * ({@code BR-PRIV-1}).
 *
 * @param type       что произошло
 * @param proposalId задача, которой касается событие
 * @param at         когда произошло (ISO-8601, как и остальные даты API)
 */
public record ProposalEvent(EventType type, UUID proposalId, String at) {
}
