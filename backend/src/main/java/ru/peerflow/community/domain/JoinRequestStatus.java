package ru.peerflow.community.domain;

/**
 * Состояние заявки на вступление в сообщество ({@code BR-JOIN-4},
 * {@code BR-JOIN-5}).
 *
 * <p>Решение принимается один раз и не пересматривается: после
 * {@link #ACCEPTED} человек уже член сообщества, после {@link #REJECTED}
 * заявка закрыта. Подать новую заявку после отказа можно — это отдельная
 * запись, чтобы история решений сохранилась.
 */
public enum JoinRequestStatus {

    /** Ждёт голосования действующих членов. */
    PENDING,

    /** Порог голосов «за» набран, человек принят в сообщество. */
    ACCEPTED,

    /** Порог недостижим или сообщество отказало. */
    REJECTED
}
