package ru.peerflow.community.domain;

/**
 * Состояние аккаунта.
 *
 * <p>Физического удаления нет: удалённый аккаунт помечается как
 * {@link #DELETED} и остаётся в базе, чтобы не рвать связи с историей
 * сообщества ({@code BR-PRIV-2}).
 */
public enum UserStatus {

    /** Действующий аккаунт. */
    ACTIVE,

    /** Аккаунт удалён владельцем; данные остаются, но аккаунт не используется. */
    DELETED
}
