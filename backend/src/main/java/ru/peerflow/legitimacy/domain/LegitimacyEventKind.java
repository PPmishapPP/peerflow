package ru.peerflow.legitimacy.domain;

/**
 * Что произошло с легитимностью по задаче ({@code BR-LEGIT-2},
 * {@code BR-LEGIT-5}).
 *
 * <p>Событий ровно два, и оба идут только «вперёд»: передача и отзыв.
 * Других переходов нет, поэтому текущее состояние всегда вычисляется как
 * последнее событие по паре «задача + член».
 */
public enum LegitimacyEventKind {

    /** Член передал свою легитимность кандидату ({@code BR-LEGIT-2}). */
    DELEGATE,

    /** Член забрал свою легитимность обратно ({@code BR-LEGIT-5}). */
    REVOKE
}
