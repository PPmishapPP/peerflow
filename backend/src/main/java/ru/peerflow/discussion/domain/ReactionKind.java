package ru.peerflow.discussion.domain;

/**
 * Реакция члена сообщества на сообщение ({@code BR-DISC-2}, {@code BR-VOTE-6}).
 *
 * <p>Отдельный тип, а не флаг «спам» рядом с «плюсом»: реакция ровно одна, и
 * три состояния должны быть взаимоисключающими на уровне типа. Иначе можно
 * было бы одновременно поставить «плюс» и «спам», и подсчёт меток разошёлся бы
 * между экраном и скрытием спама.
 *
 * <p>Не путать с голосом «делаем / не делаем» ({@code BR-VOTE-4}): это разные
 * шкалы, и голос по решению не влияет на ранжирование сообщений.
 */
public enum ReactionKind {

    /** «По делу и согласен» — поднимает сообщение ({@code BR-DISC-4}). */
    PLUS,

    /** «По делу, но не согласен» — понижает при равенстве плюсов ({@code BR-DISC-4}). */
    MINUS,

    /**
     * «Не по делу» — при достаточном числе меток сообщение скрывается
     * ({@code BR-SPAM-1}).
     */
    SPAM
}
