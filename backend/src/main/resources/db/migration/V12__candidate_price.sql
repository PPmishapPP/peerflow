-- V12__candidate_price.sql
--
-- Бюджет как обязательство исполнителя: цена кандидата и бюджет задачи
-- (BR-BUDGET-2, BR-BUDGET-3, BR-BUDGET-7, BR-BUDGET-8, BR-BUDGET-9,
-- BR-LIFE-1, BR-LIFE-6, BR-LIFE-10, BR-LEADER-1).
--
-- Почему цена переехала к кандидату. Раньше бюджет задавал автор предложения,
-- и «новый бюджет» при утрате мандата был отдельной операцией, которой в
-- системе не существовало: BR-LIFE-10 и BR-BUDGET-7 требовали её, а коду
-- было негде её выразить. Теперь цену называет тот, кто берётся выполнять
-- задачу, и смена лидера сама меняет бюджет: новое обязательство — новая
-- цена. Правило перестало быть отдельным действием и стало следствием модели.
--
-- Что где лежит:
--   proposal.budget       — потолок, утверждённый сообществом: больше этой
--                           суммы задача стоить не может (BR-BUDGET-2,
--                           BR-BUDGET-3). Не меняется никогда;
--   candidate.price       — цена, за которую человек берётся (BR-BUDGET-8);
--   proposal.task_budget  — бюджет текущей попытки: цена победившего
--                           кандидата (BR-LIFE-6). Пусто, пока лидера нет,
--                           и сбрасывается при возврате на переголосование
--                           (BR-BUDGET-7).
--
-- Двух «правд» здесь нет: task_budget — это ровно цена действующего мандата,
-- и пишет её только выдача мандата.

-- Потолок остаётся у автора: BR-LIFE-1 и BR-BUDGET-2 никуда не делись, автор
-- по-прежнему обязан назвать сумму. Меняется смысл: это верхняя граница.
COMMENT ON COLUMN proposal.budget IS
    'Потолок бюджета, утверждённый сообществом (BR-BUDGET-2, BR-BUDGET-3)';

-- Цена кандидата: за сколько он выполнит задачу (BR-BUDGET-8).
--
-- NOT NULL и CHECK > 0 — по тому же принципу, что и потолок: «кандидат без
-- цены» не отвечает на вопрос, ради которого его выдвигают. Заполнение для
-- уже выдвинутых кандидатов — потолок задачи: до этой миграции цена не
-- выбиралась, и «берусь за всю утверждённую сумму» — самое честное прочтение.
ALTER TABLE candidate
    ADD COLUMN price bigint;

UPDATE candidate candidate
SET price = proposal.budget
FROM proposal
WHERE proposal.id = candidate.proposal_id;

ALTER TABLE candidate
    ALTER COLUMN price SET NOT NULL,
    ADD CONSTRAINT ck_candidate_price CHECK (price > 0);

COMMENT ON COLUMN candidate.price IS
    'Цена, за которую кандидат выполнит задачу (BR-BUDGET-8)';

-- Бюджет текущей попытки: цена победившего кандидата (BR-LIFE-6).
--
-- Отдельно от потолка, потому что сообщество утверждает границу, а лидер
-- берётся за конкретную сумму внутри неё. Пусто, пока лидера нет: задача
-- может быть принята «делаем» и ждать исполнителя.
ALTER TABLE proposal
    ADD COLUMN task_budget bigint;

ALTER TABLE proposal
    ADD CONSTRAINT ck_proposal_task_budget
        CHECK (task_budget IS NULL OR task_budget > 0);

COMMENT ON COLUMN proposal.task_budget IS
    'Бюджет текущего мандата — цена победившего кандидата (BR-LIFE-6, BR-LIFE-10)';
